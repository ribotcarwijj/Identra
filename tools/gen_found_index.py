#!/usr/bin/env python3
"""
Generates app/src/main/java/dev/identra/app/found/FoundIndexData.java from every
app/src/main/assets/**/hooks.json (except __deprecated).

The index is what "Found in this app" (0.6.0) matches against, both in the Identra app
(static dex scan) and inside hooked app processes (observe mode), so it has to be plain
Java data: no asset IO, no JSON parsing at app start.

One row per hook, tab separated:
  id \t group \t className \t methodName \t params(comma) \t settings(comma) \t returnType

Run from the repo root:  python3 tools/gen_found_index.py
CI runs it before every build (work-debug.yml), so the index always matches the hooks.
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, "app", "src", "main", "assets")
OUT = os.path.join(ROOT, "app", "src", "main", "java", "dev", "identra", "app", "found", "FoundIndexData.java")


def strip_lenient(s):
    """org.json-style leniency: // and /* */ comments outside strings, trailing commas."""
    out, i, n, in_str = [], 0, len(s), False
    while i < n:
        c = s[i]
        if in_str:
            out.append(c)
            if c == "\\" and i + 1 < n:
                out.append(s[i + 1]); i += 2; continue
            if c == '"':
                in_str = False
            i += 1; continue
        if c == '"':
            in_str = True; out.append(c); i += 1; continue
        if s.startswith("//", i):
            j = s.find("\n", i); i = n if j < 0 else j; continue
        if s.startswith("/*", i):
            j = s.find("*/", i + 2); i = n if j < 0 else j + 2; continue
        if c == "#":
            j = s.find("\n", i); i = n if j < 0 else j; continue
        out.append(c); i += 1
    t = "".join(out)
    t = re.sub(r",\s*([\]}])", r"\1", t)
    return t


def clean(v):
    return str(v).replace("\t", " ").replace("\n", " ").replace("\r", " ").strip()


def main():
    rows, seen, errors = [], set(), []
    for f in sorted(glob.glob(os.path.join(ASSETS, "**", "hooks.json"), recursive=True)):
        rel = os.path.relpath(f, ASSETS)
        if rel.startswith("__deprecated"):
            continue
        try:
            data = json.loads(strip_lenient(open(f, encoding="utf-8").read()))
        except Exception as e:  # keep going, report at the end
            errors.append("%s: %s" % (rel, e)); continue
        for h in data:
            if not isinstance(h, dict):
                continue
            name, coll = h.get("name"), h.get("collection") or "Identra"
            cls, meth = h.get("className"), h.get("methodName")
            if not name or not cls or not meth:
                continue
            if h.get("enabled") is False:   # disabled hooks never show up as found
                continue
            hid = "%s.%s" % (coll, name)
            if hid in seen:
                continue
            seen.add(hid)
            params = ",".join(clean(p) for p in (h.get("parameterTypes") or []))
            settings = ",".join(clean(p) for p in (h.get("settings") or []))
            rows.append("\t".join([clean(hid), clean(h.get("group") or ""), clean(cls), clean(meth),
                                   params, settings, clean(h.get("returnType") or "")]))
    if errors:
        sys.stderr.write("gen_found_index: could not parse:\n  " + "\n  ".join(errors) + "\n")
        sys.exit(1)

    def jstr(s):
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t") + '"'

    body = ",\n            ".join(jstr(r) for r in rows)
    java = """package dev.identra.app.found;

// GENERATED by tools/gen_found_index.py from assets/**/hooks.json - do not edit by hand.
// CI regenerates it before every build.
final class FoundIndexData {
    private FoundIndexData() { }

    /** id, group, className, methodName, params, settings, returnType (tab separated). */
    static final String[] ROWS = {
            %s
    };
}
""" % body
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(java)
    print("gen_found_index: %d hooks -> %s" % (len(rows), os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    main()
